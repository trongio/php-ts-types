<?php

declare(strict_types=1);

namespace Trongio\PhpTsTypes\Emitter;

use Trongio\PhpTsTypes\Exceptions\UnresolvedReference;
use Trongio\PhpTsTypes\Exceptions\UnsupportedType;
use Trongio\PhpTsTypes\Type\Json;
use Trongio\PhpTsTypes\Type\ListType;
use Trongio\PhpTsTypes\Type\Literal;
use Trongio\PhpTsTypes\Type\ObjectType;
use Trongio\PhpTsTypes\Type\Primitive;
use Trongio\PhpTsTypes\Type\Property;
use Trongio\PhpTsTypes\Type\RecordType;
use Trongio\PhpTsTypes\Type\Reference;
use Trongio\PhpTsTypes\Type\Type;
use Trongio\PhpTsTypes\Type\TypeDefinitions;
use Trongio\PhpTsTypes\Type\Union;
use Trongio\PhpTsTypes\Type\Wrapped;

/**
 * Renders {@see TypeDefinitions} as one TypeScript module: the header, then `export type Name = ...;` per name,
 * sorted, then the raw `append` block (for a `declare module` augmentation). Only `export type`: no
 * `interface`, `any`, `unknown` or `{}` is ever emitted (any JSON value is the named recursive {@see Json}), and the output is clean under `verbatimModuleSyntax`.
 * Keys are emitted verbatim, quoted only when they are not identifiers. The output is deterministic.
 */
final class TypeScriptEmitter
{
    public const string DEFAULT_HEADER = '// Generated by trongio/php-ts-types, do not edit.';

    public function emit(TypeDefinitions $definitions, string $header = self::DEFAULT_HEADER, string $append = ''): string
    {
        $blocks = [];

        foreach ($definitions->all() as $name => $type) {
            $blocks[] = 'export type '.$name.' = '.$this->top($type, $definitions, $name).";\n";
        }

        $output = rtrim($header)."\n\n".implode("\n", $blocks);

        return trim($append) === '' ? $output : $output."\n".rtrim($append)."\n";
    }

    /** A top-level object is written one key per line, with its descriptions; anything else inline. */
    private function top(Type $type, TypeDefinitions $definitions, string $where): string
    {
        if ($type instanceof Json) {
            return 'string | number | boolean | null | '.Json::NAME.'[] | { [key: string]: '.Json::NAME.' }';
        }

        if (! $type instanceof ObjectType || $type->properties === []) {
            return $this->inline($type, $definitions, $where);
        }

        $lines = [];

        foreach ($type->properties as $property) {
            if ($property->description !== '') {
                $lines[] = "\t/** ".str_replace('*/', '* /', $property->description).' */';
            }

            $lines[] = "\t".$this->property($property, $definitions, $where).';';
        }

        return "{\n".implode("\n", $lines)."\n}";
    }

    private function property(Property $property, TypeDefinitions $definitions, string $where): string
    {
        $type = $property->type instanceof Wrapped ? $property->type->inner : $property->type;

        return self::key($property->name).($property->isOptional() ? '?' : '').': '
            .$this->inline($type, $definitions, $where.'.'.$property->name);
    }

    private function inline(Type $type, TypeDefinitions $definitions, string $where): string
    {
        return match (true) {
            $type instanceof Primitive => $type->name,
            $type instanceof Literal => self::literal($type->value),
            $type instanceof Union => implode(' | ', array_map(
                fn (Type $member): string => $this->inline($member, $definitions, $where),
                $type->members,
            )),
            $type instanceof ListType => $type->item instanceof Union
                ? '('.$this->inline($type->item, $definitions, $where.'[]').')[]'
                : $this->inline($type->item, $definitions, $where.'[]').'[]',
            $type instanceof RecordType => 'Record<string, '.$this->inline($type->value, $definitions, $where.'{}').'>',
            $type instanceof ObjectType => $type->properties === []
                ? 'Record<string, never>'
                : '{ '.implode('; ', array_map(
                    fn (Property $property): string => $this->property($property, $definitions, $where),
                    $type->properties,
                )).' }',
            $type instanceof Reference => $definitions->has($type->name)
                ? $type->name
                : throw new UnresolvedReference($type->name, $where),
            $type instanceof Json => $definitions->has(Json::NAME)
                ? Json::NAME
                : throw new UnresolvedReference(Json::NAME, $where),
            $type instanceof Wrapped => throw new UnsupportedType($where, $type->kind->value.' outside a property'),
            default => throw new UnsupportedType($where, $type::class),
        };
    }

    /** An object key: verbatim when it is an identifier, else a string literal. */
    public static function key(string $name): string
    {
        return preg_match('/^[A-Za-z_$][A-Za-z0-9_$]*$/', $name) === 1 ? $name : self::literal($name);
    }

    public static function literal(string|int|bool $value): string
    {
        return match (true) {
            is_string($value) => json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR),
            is_bool($value) => $value ? 'true' : 'false',
            default => (string) $value,
        };
    }
}
